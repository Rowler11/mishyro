#!/usr/bin/env python3
"""Self-host the app fonts with only the glyphs we use.

Dev tool (not part of the app runtime). Requires: pip install fonttools brotli
and the font packages installed with npm in NODE_MODULES:
  npm i @expo-google-fonts/shippori-mincho @expo-google-fonts/zen-maru-gothic @expo-google-fonts/atkinson-hyperlegible
(those packages ship the full Google Fonts TTF files)

Usage: python3 tools/subset-fonts.py NODE_MODULES [--cn-only]
v0.16.0: the Chinese styles' title fonts (Ma Shan Zheng, Noto Serif SC) take only the
characters found in js/core/letters.js; --cn-only regenerates just those two files.
Needs also: npm i @expo-google-fonts/ma-shan-zheng @expo-google-fonts/noto-serif-sc
Writes fonts/*.woff2 and fonts/fonts.css. Japanese glyphs come from
JA_TEXT below plus every CJK/kana character found in js/ and index.html.
"""
import re, sys, pathlib, io
from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = pathlib.Path(__file__).resolve().parent.parent
NM = pathlib.Path(sys.argv[1])
OUT = ROOT / "fonts"
OUT.mkdir(exist_ok=True)

# Closed table of Japanese labels (docs/02) + decoration.
JA_TEXT = ("今思い出券手紙もっとおみくじ願い写真クイズ日記歌記念日設定地図タイムカプセルバッジ年間想い"
           "デートガチャ貯金プリクラ次回贈り物挑戦カレンダー初めて気分おはようおやすみ周期秘密ペット招き猫"
           "情報夜アルバム夢レシピ声お知らせ遊び折り紙七夕言葉漫画映画季節感謝振り返り当たり習慣家計リスト自分愛"
           "愛してる二人桜")

def used_cjk():
    chars = set(JA_TEXT)
    for p in list((ROOT / "js").rglob("*.js")) + [ROOT / "index.html"]:
        if p.exists() and p.name != "letters.js":
            chars |= set(re.findall(r"[぀-ヿ㐀-鿿＀-￯]", p.read_text("utf-8")))
    return chars

# Latin coverage for Spanish UI (Basic Latin, Latin-1, General Punctuation subset, currency, arrows).
LATIN = "U+0020-007E,U+00A0-00FF,U+0131,U+0152-0153,U+02C6,U+02DA,U+02DC,U+2013-2014,U+2018-201E,U+2022,U+2026,U+20AC,U+2190-2193,U+00B7,U+2122"

FAMILIES = [
    # (npm package, CSS family, weight, ttf path inside the package, include Japanese)
    ("shippori-mincho", "Shippori Mincho", 400, "400Regular/ShipporiMincho_400Regular.ttf", True),
    ("shippori-mincho", "Shippori Mincho", 700, "700Bold/ShipporiMincho_700Bold.ttf", True),
    ("zen-maru-gothic", "Zen Maru Gothic", 400, "400Regular/ZenMaruGothic_400Regular.ttf", True),
    ("zen-maru-gothic", "Zen Maru Gothic", 500, "500Medium/ZenMaruGothic_500Medium.ttf", True),
    ("zen-maru-gothic", "Zen Maru Gothic", 700, "700Bold/ZenMaruGothic_700Bold.ttf", True),
    ("atkinson-hyperlegible", "Atkinson Hyperlegible", 400, "400Regular/AtkinsonHyperlegible_400Regular.ttf", False),
    ("atkinson-hyperlegible", "Atkinson Hyperlegible", 700, "700Bold/AtkinsonHyperlegible_700Bold.ttf", False),
]

# Chinese styles (v0.16.0): title letters only, no Latin. Each file is a few KB.
CN_FAMILIES = [
    ("ma-shan-zheng", "Ma Shan Zheng", 400, "400Regular/MaShanZheng_400Regular.ttf"),
    ("noto-serif-sc", "Noto Serif SC", 700, "700Bold/NotoSerifSC_700Bold.ttf"),
]

def cn_chars():
    return {ord(c) for c in re.findall(r"[㐀-鿿]", (ROOT / "js" / "core" / "letters.js").read_text("utf-8"))}

def cn_fonts():
    css = []
    cps = sorted(cn_chars())
    for slug, name, w, ttf in CN_FAMILIES:
        font = TTFont(NM / "@expo-google-fonts" / slug / ttf)
        opts = subset.Options(); opts.flavor = "woff2"
        sub = subset.Subsetter(opts); sub.populate(unicodes=cps); sub.subset(font)
        font.flavor = "woff2"
        dst = OUT / f"{slug}-{w}.woff2"; font.save(dst)
        css.append("@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:swap;src:url(./%s) format('woff2')}" % (name, w, dst.name))
    return css

def parse_ranges(rng):
    out = set()
    for part in rng.split(","):
        part = part.strip().replace("U+", "")
        if "-" in part:
            a, b = part.split("-"); out |= set(range(int(a, 16), int(b, 16) + 1))
        elif part:
            out.add(int(part, 16))
    return out

def main():
    if "--cn-only" in sys.argv:
        old = [l for l in (OUT / "fonts.css").read_text("utf-8").splitlines() if "Ma Shan Zheng" not in l and "Noto Serif SC" not in l]
        (OUT / "fonts.css").write_text("\n".join(old + cn_fonts()) + "\n", "utf-8")
        print("ok cn"); return
    cjk = sorted({ord(c) for c in used_cjk()})
    latin = sorted(parse_ranges(LATIN))
    css = ["/* Generated by tools/subset-fonts.py. Fonts: SIL Open Font License 1.1 (see fonts/LICENSES.md). */"]
    for slug, name, w, ttf, has_ja in FAMILIES:
        src = NM / "@expo-google-fonts" / slug / ttf
        cps = latin + (cjk if has_ja else [])
        font = TTFont(src)
        cmap = font.getBestCmap()
        missing = [chr(c) for c in cjk if has_ja and c not in cmap]
        if missing:
            print("WARNING missing in", name, w, "".join(missing))
        opts = subset.Options(); opts.flavor = "woff2"; opts.layout_features = ["kern", "liga", "palt", "tnum", "lnum"]
        sub = subset.Subsetter(opts); sub.populate(unicodes=cps); sub.subset(font)
        font.flavor = "woff2"
        dst = OUT / f"{slug}-{w}.woff2"; font.save(dst)
        css.append("@font-face{font-family:'%s';font-style:normal;font-weight:%d;font-display:swap;src:url(./%s) format('woff2')}" % (name, w, dst.name))
    css += cn_fonts()
    (OUT / "fonts.css").write_text("\n".join(css) + "\n", "utf-8")
    print("ok", len(list(OUT.glob('*.woff2'))), "files")

if __name__ == "__main__":
    main()
